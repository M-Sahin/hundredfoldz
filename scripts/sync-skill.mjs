#!/usr/bin/env node
// Copies the mtg-master Claude skill into lib/skill/content.ts, so Claude's system prompt is
// built from the skill itself. The skill lives in its own repository; package.json pins the
// release this app uses ("skill": { "repo", "ref" }).
//   npm run sync-skill              write content.ts from the pinned release
//   npm run check-skill             fail if content.ts doesn't match the pinned release (CI)
//   SKILL_DIR=../mtg-master/mtg-master npm run sync-skill
//                                   use a local copy of the skill folder instead (while editing it)
// To move to a new skill release: change "ref" in package.json, run npm run sync-skill, commit both.
// content.ts is committed, so building and deploying never need the skill repository.
import { readFileSync, writeFileSync, existsSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const out = join(root, "lib", "skill", "content.ts");
const check = process.argv.includes("--check");
const pin = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).skill;
if (!pin?.repo || !pin?.ref) {
  console.error('sync-skill: package.json needs "skill": { "repo": "...", "ref": "v1.2.3" }');
  process.exit(2);
}

const FILES = ["SKILL.md", "references/commander.md", "references/lookup.md", "references/constructed.md", "references/rules.md"];

let skillDir;
let source;
let version;
let cleanup = () => {};
if (process.env.SKILL_DIR) {
  skillDir = resolve(process.env.SKILL_DIR);
  if (!existsSync(join(skillDir, "SKILL.md"))) {
    console.error(`sync-skill: no SKILL.md in ${skillDir} (point SKILL_DIR at the mtg-master/ folder inside the skill repo)`);
    process.exit(2);
  }
  source = `local copy ${process.env.SKILL_DIR}`;
  const readme = join(skillDir, "..", "README.md");
  version = (existsSync(readme) && (readFileSync(readme, "utf8").match(/\*\*(\d+\.\d+\.\d+)\*\*/) || [])[1]) || "dev";
} else {
  const tmp = mkdtempSync(join(tmpdir(), "mtg-master-"));
  cleanup = () => rmSync(tmp, { recursive: true, force: true });
  try {
    execFileSync("git", ["-c", "advice.detachedHead=false", "clone", "-q", "--depth", "1", "--branch", pin.ref, pin.repo, tmp], { stdio: ["ignore", "ignore", "inherit"] });
  } catch {
    cleanup();
    console.error(`sync-skill: couldn't fetch ${pin.repo} at ${pin.ref}`);
    process.exit(2);
  }
  skillDir = join(tmp, "mtg-master");
  source = `${pin.repo.replace(/^https:\/\/github\.com\//, "").replace(/\.git$/, "")}@${pin.ref}`;
  version = /^v\d+\.\d+\.\d+$/.test(pin.ref)
    ? pin.ref.slice(1)
    : (readFileSync(join(tmp, "README.md"), "utf8").match(/\*\*(\d+\.\d+\.\d+)\*\*/) || [])[1] || pin.ref;
}

try {
  const entries = Object.fromEntries(FILES.map((f) => [f, readFileSync(join(skillDir, f), "utf8")]));
  const body =
    `// GENERATED by scripts/sync-skill.mjs from the mtg-master skill (${source}). Do not edit by hand.\n` +
    `export const SKILL_VERSION = ${JSON.stringify(version)};\n` +
    `export const SKILL_FILES: Record<string, string> = ${JSON.stringify(entries, null, 2)};\n`;
  if (check) {
    const current = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (current !== body) {
      console.error(`lib/skill/content.ts doesn't match the skill at ${source}. Run: npm run sync-skill`);
      process.exitCode = 1;
    } else console.log(`sync-skill: up to date with ${source}`);
  } else {
    writeFileSync(out, body);
    console.log(`sync-skill: wrote lib/skill/content.ts from ${source} (${FILES.length} files, skill ${version}, ${entries["SKILL.md"].length} chars in SKILL.md)`);
  }
} finally {
  cleanup();
}
